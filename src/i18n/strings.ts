/** 语言标签映射(设置面板下拉用)。 */
export const LANGUAGE_LABELS: Record<string, UiLocale> = {
  "": "zh",
  zh: "zh",
  en: "en",
};

/** key 优先查 en 表,缺失回退返回 key(中文原文);支持 {name} 插值。 */
export function t(key: string, locale: UiLocale, params?: Record<string, string | number>): string {
  const template = locale === "en" ? (en[key] ?? key) : key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    params[name] !== undefined ? String(params[name]) : `{${name}}`,
  );
}
